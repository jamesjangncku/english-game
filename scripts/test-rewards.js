#!/usr/bin/env node
'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs'),vm=require('node:vm');
const context={window:{}};
vm.runInNewContext(fs.readFileSync('reward-art.js','utf8'),context,{timeout:10000});
vm.runInNewContext(fs.readFileSync('rewards.js','utf8'),context,{timeout:10000});
const items=context.window.GAME_REWARDS;
const rule=context.window.GAME_REWARD_RULES;
const art=context.window.GAME_REWARD_ART;
assert.equal(items.length,12);
assert.equal(new Set(Array.from(items,x=>x.id)).size,12);
assert.deepEqual(Array.from(items,x=>x.category==='outfit').filter(Boolean).length,4);
assert.deepEqual(Array.from(items,x=>x.category==='scene').filter(Boolean).length,4);
assert.deepEqual(Array.from(items,x=>x.category==='badge').filter(Boolean).length,4);
for(const item of items){
 assert(Number.isInteger(item.price)&&item.price>0);
 assert(['普通','稀有','傳說'].includes(item.rarity));
 assert(art.svg(item.id).startsWith('<svg'));
 assert(art.svg(item.id).includes('</svg>'));
 assert(art.item(item.id).startsWith('data:image/svg+xml'));
}
const worn=art.portrait({hat:'magic-hat',cape:'hero-cape',glasses:'star-glasses'});
assert(worn.startsWith('data:image/svg+xml'));
assert(worn.length>1000);
assert.equal(rule.pointsForAnswer(false),10);
assert.equal(rule.pointsForAnswer(true),2);
assert.equal(rule.canBuy(99,[],'magic-hat'),false);
assert.equal(rule.canBuy(100,[],'magic-hat'),true);
const bought=rule.buy(100,[],'magic-hat');
assert.equal(bought.stars,0);
assert.deepEqual(Array.from(bought.owned),['magic-hat']);
assert.equal(rule.canBuy(100,bought.owned,'magic-hat'),false);
assert.equal(rule.buy(100,bought.owned,'magic-hat'),null);
assert.equal(rule.buy(20,[],'castle'),null);
assert.equal(rule.buy(100,[],'unknown-reward'),null);
for(const id of ['magic-hat','hero-cape','treehouse','castle'])assert(items.some(x=>x.id===id),'V8 reward missing: '+id);
const game=fs.readFileSync('game.js','utf8'),html=fs.readFileSync('index.html','utf8');
assert(html.includes('id="navShop"')&&html.includes('id="shopItems"')&&html.includes('id="collectionShelf"')&&html.includes('id="shopFilters"'));
assert(html.includes('<script src="reward-art.js"></script><script src="approved-art.js"></script><script src="rewards.js"></script><script src="game.js"></script>'));
assert(fs.existsSync('assets/v9-approved-art-atlas.svg'));
assert(fs.readFileSync('assets/v9-approved-art-atlas.svg','utf8').includes('data:image/webp;base64,'));
assert(game.includes("state.correctIds.includes(q.id)"));
assert(game.includes("GAME_REWARD_RULES.pointsForAnswer"));
assert(game.includes("function renderShop()"));
assert(game.includes("GAME_APPROVED_ART.apply"));
assert(fs.existsSync("approved-art.js"));
assert(!game.includes("unlockLesson")&&!game.includes("requiredStars"));
const dataContext={window:{}};vm.runInNewContext(fs.readFileSync('data.js','utf8'),dataContext,{timeout:10000});
const catalog=dataContext.window.GAME_CATALOG,qs=dataContext.window.GAME_QUESTIONS;
assert.equal(qs.length,997);
const uncovered=[];
for(const book of catalog)for(const unit of book.units)for(const lesson of unit.lessons)if(!qs.some(x=>x.book===book.id&&x.unit===unit.id&&x.lesson===lesson.id))uncovered.push([book.id,unit.id,lesson.id].join('/'));
assert.deepEqual(uncovered,[]);
console.log('PASS: 12 illustrated V9 rewards, persistent V8 IDs, pricing, purchases, artwork, 997 questions and all lessons freely accessible');
