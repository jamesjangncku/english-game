#!/usr/bin/env node
'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs'),vm=require('node:vm');
const context={window:{}};
vm.runInNewContext(fs.readFileSync('rewards.js','utf8'),context,{timeout:10000});
const rewards=context.window.GAME_REWARDS;
const rules=context.window.GAME_REWARD_RULES;
assert.equal(rewards.length,4);
assert.deepEqual(Array.from(rewards,x=>x.price),[100,200,500,1000]);
assert.equal(new Set(Array.from(rewards,x=>x.id)).size,rewards.length);
assert.equal(rules.pointsForAnswer(false),10);
assert.equal(rules.pointsForAnswer(true),2);
assert.equal(rules.canBuy(99,[],'magic-hat'),false);
assert.equal(rules.canBuy(100,[],'magic-hat'),true);
let purchase=rules.buy(100,[],'magic-hat');
assert.equal(purchase.stars,0);
assert.deepEqual(Array.from(purchase.owned),['magic-hat']);
assert.equal(rules.canBuy(100,purchase.owned,'magic-hat'),false);
assert.equal(rules.buy(100,purchase.owned,'magic-hat'),null);
assert.equal(rules.buy(20,[],'castle'),null);
assert.equal(rewards.every(x=>['hat','cape','home'].includes(x.slot)),true);
const game=fs.readFileSync('game.js','utf8'),html=fs.readFileSync('index.html','utf8');
assert(html.includes('id="navShop"')&&html.includes('id="shopItems"'));
assert(html.includes('<script src="rewards.js"></script><script src="game.js"></script>'));
assert(game.includes("state.correctIds.includes(q.id)"));
assert(game.includes("GAME_REWARD_RULES.pointsForAnswer"));
assert(game.includes("function renderShop()"));
assert(!game.includes("unlockLesson")&&!game.includes("requiredStars"));
console.log('PASS: shop products, first/repeat rewards, sufficient balance, no duplicate purchases, navigation, open lessons');
